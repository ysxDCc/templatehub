/**
 * Multi-Format Template Transpiler
 * Converts raw standalone HTML5 into clean React / Next.js (TSX), Astro, and Vue 3 SFC
 */

export type CodeFormat = 'html' | 'jsx' | 'astro' | 'vue';

const SVG_ATTR_MAP: Record<string, string> = {
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-dasharray': 'strokeDasharray',
  'stroke-dashoffset': 'strokeDashoffset',
  'stroke-opacity': 'strokeOpacity',
  'fill-rule': 'fillRule',
  'fill-opacity': 'fillOpacity',
  'clip-rule': 'clipRule',
  'clip-path': 'clipPath',
  'stop-color': 'stopColor',
  'stop-opacity': 'stopOpacity',
  'font-family': 'fontFamily',
  'font-size': 'fontSize',
  'font-weight': 'fontWeight',
  'text-anchor': 'textAnchor',
};

const HTML_VOID_ELEMENTS = [
  'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input',
  'link', 'meta', 'param', 'source', 'track', 'wbr'
];

/**
 * Converts inline style strings like "color: red; font-size: 14px;" into JSX style objects
 */
function convertInlineStylesToJsx(html: string): string {
  return html.replace(/style="([^"]*)"/gi, (_, styleStr) => {
    const rules = styleStr
      .split(';')
      .map((r: string) => r.trim())
      .filter(Boolean);

    const styleObj: Record<string, string> = {};
    for (const rule of rules) {
      const colonIdx = rule.indexOf(':');
      if (colonIdx === -1) continue;
      const prop = rule.slice(0, colonIdx).trim();
      const val = rule.slice(colonIdx + 1).trim();
      // CamelCase property
      const camelProp = prop.replace(/-([a-z])/g, (_: string, letter: string) => letter.toUpperCase());
      styleObj[camelProp] = val;
    }

    return `style={${JSON.stringify(styleObj)}}`;
  });
}

/**
 * Closes unclosed void elements (e.g. <img src="..."> -> <img src="..." />)
 */
function selfCloseVoidTags(html: string): string {
  let result = html;
  for (const tag of HTML_VOID_ELEMENTS) {
    // Match <tag ...> where there is no closing slash before >
    const regex = new RegExp(`<(${tag})((?:\\s+[^>]*)?)(?<!\\/)>`, 'gi');
    result = result.replace(regex, '<$1$2 />');
  }
  return result;
}

/**
 * Converts raw HTML into clean React / Next.js TSX component
 */
export function convertHtmlToReact(html: string, componentName: string = 'TemplateComponent'): string {
  let bodyContent = html;

  // Extract content between <body> and </body> if present
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i);
  if (bodyMatch) {
    bodyContent = bodyMatch[1].trim();
  }

  // 1. Replace class with className
  bodyContent = bodyContent.replace(/\bclass="/g, 'className="');
  bodyContent = bodyContent.replace(/\bclass='/g, "className='");

  // 2. Replace for with htmlFor
  bodyContent = bodyContent.replace(/\bfor="/g, 'htmlFor="');
  bodyContent = bodyContent.replace(/\bfor='/g, "htmlFor='");

  // 3. Convert SVG hyphenated attributes
  for (const [hyphenated, camel] of Object.entries(SVG_ATTR_MAP)) {
    const re = new RegExp(`\\b${hyphenated}="`, 'g');
    bodyContent = bodyContent.replace(re, `${camel}="`);
  }

  // 4. Convert inline styles
  bodyContent = convertInlineStylesToJsx(bodyContent);

  // 5. Close void tags
  bodyContent = selfCloseVoidTags(bodyContent);

  // 6. Escape lone curly braces not in template expressions
  bodyContent = bodyContent.replace(/\{(?!\s*["'{])/g, '&#123;');

  const sanitizedComponentName = componentName.replace(/[^a-zA-Z0-9]/g, '');

  return `// Next.js (App Router / Pages Router) & React 19 Component
// Transpiled automatically from TemplateHub Sovereign Masterpiece
'use client';

import React from 'react';

export default function ${sanitizedComponentName}() {
  return (
    <>
      ${bodyContent}
    </>
  );
}
`;
}

/**
 * Converts raw HTML into Astro component layout
 */
export function convertHtmlToAstro(html: string, templateName: string): string {
  let bodyContent = html;
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i);
  if (bodyMatch) {
    bodyContent = bodyMatch[1].trim();
  }

  return `---
// Astro Component Layout — Generated by TemplateHub
// High-performance static output with zero JS footprint
interface Props {
  title?: string;
}

const { title = "${templateName} — TemplateHub" } = Astro.props;
---

<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>{title}</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  </head>
  <body>
    ${bodyContent}
  </body>
</html>
`;
}

/**
 * Converts raw HTML into Vue 3 SFC (<template> + <script setup>)
 */
export function convertHtmlToVue(html: string, templateName: string): string {
  let bodyContent = html;
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i);
  if (bodyMatch) {
    bodyContent = bodyMatch[1].trim();
  }

  return `<script setup lang="ts">
// Vue 3 Single File Component (SFC)
// Generated by TemplateHub Sovereign Engine
defineProps<{
  pageTitle?: string;
}>();
</script>

<template>
  <div class="templatehub-container">
    ${bodyContent}
  </div>
</template>

<style scoped>
/* Inherits global styles or insert scoped customizations here */
</style>
`;
}
